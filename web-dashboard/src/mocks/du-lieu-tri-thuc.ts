/** Rút gọn một đoạn thành bản ghi đầy đủ — mọi đoạn cùng mô hình nhúng và cùng phiên bản. */
function doan(
  id: string,
  ordinal: number,
  sectionPath: string,
  content: string,
): DoanTaiLieu {
  return {
    id,
    ordinal,
    content,
    sectionPath,
    // Xấp xỉ: tiếng Việt khoảng 1 token cho mỗi 3 ký tự với bộ tách từ của mô hình đa ngữ
    tokenCount: Math.round(content.length / 3),
    embeddingModel: 'BAAI/bge-m3',
    embeddingVersion: 'v1',
  }
}

